'use strict';
const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
async function main() {
  const [base, out, executablePath] = process.argv.slice(2);
  const { chromium } = require(process.env.PREVIEW_PLAYWRIGHT_PATH);
  fs.mkdirSync(out, { recursive: true });
  const browser = await chromium.launch({ headless: true, executablePath });
  const p = await browser.newPage();
  const errors = [];
  p.on('pageerror', e => errors.push(e.message));
  // Explicit fixture navigation may reset unfinished synthetic content.
  p.on('dialog', d => d.accept());
  const png = { name: 'synthetic.png', mimeType: 'image/png', buffer: Buffer.from('iVBORw0KGgoAAAANSUhEUgAAAAEAAAABCAQAAAC1HAwCAAAAC0lEQVR42mP8/x8AAusB9Y9ZlGQAAAAASUVORK5CYII=', 'base64') };
  const nav = code => p.locator('[data-screen="' + code + '"]').click();
  const action = name => p.locator('[data-action="' + name + '"]');
  const position = () => p.evaluate(() => ({ outer: scrollY, inner: document.getElementById('provider-scroll').scrollTop }));
  const focus = selector => p.locator(selector).evaluate(e => e === document.activeElement);
  try {
    for (const width of [320, 375, 414, 1280]) {
      await p.setViewportSize({ width, height: 1000 });
      await p.goto(base + '/v10.html');
      await nav('C');
      await p.locator('#p-name').fill('本次接单资料');
      await p.locator('#p-services').fill('家电维修，先沟通故障现象。');
      await p.locator('#p-region').check();
      const upload = p.locator('label[for=images]');
      await upload.scrollIntoViewIfNeeded();
      await upload.focus();
      const before = await position();
      const images = p.waitForEvent('filechooser');
      await p.keyboard.press('Enter');
      await (await images).setFiles([png, { ...png, name: 'second.png' }]);
      assert(await focus('label[for=images]'), 'image redraw must restore upload focus');
      const after = await position();
      for (const key of Object.keys(before)) assert(Math.abs(before[key] - after[key]) <= 2, key + ' retained');
      assert.equal(await p.locator('#p-name').inputValue(), '本次接单资料');
      if (width === 375) await p.screenshot({ path: path.join(out, 'provider-images-375.png'), fullPage: true });
      await p.locator('[data-remove-image="0"]').click();
      assert(await focus('[data-remove-image="0"]'));
      await p.locator('label[for=license]').focus();
      const chooser = p.waitForEvent('filechooser');
      await p.keyboard.press('Space');
      await (await chooser).setFiles(png);
      assert(await focus('label[for=license]'));
      await action('remove-license').click();
      assert(await focus('label[for=license]'));
      await p.locator('[data-remove-image="0"]').click();
      assert(await focus('label[for=images]'));
      await action('save').click();
      assert((await p.locator('#content').textContent()).includes('本次接单资料'));
      await nav('D');
      await action('add-slot').click();
      assert(await focus('#day-0'));
      assert(await p.locator('#toast').isHidden(), 'old saved notice must not describe new unsaved rows');
      await p.locator('[data-time=start]').fill('08:00');
      await p.locator('[data-time=end]').fill('12:00');
      await action('add-slot').click();
      assert(await focus('#day-1'));
      assert(await p.locator('#day-1').evaluate(e => { const r=e.getBoundingClientRect(); return r.top>=0&&r.bottom<=innerHeight; }));
      assert.equal(await p.locator('[data-time=start]').first().inputValue(), '08:00');
      if (width === 375) await p.screenshot({ path: path.join(out, 'provider-schedule-375.png'), fullPage: true });
      await p.locator('#day-1').selectOption('2');
      await p.locator('[data-remove-slot="0"]').click();
      assert(await focus('[data-remove-slot="0"]'));
      assert.equal(await p.locator('#day-0').inputValue(), '2');
      await p.locator('.schedule-target[value=errands]').check();
      assert(await focus('.schedule-target[value=errands]'));
      await action('save').click();
      await p.locator('#cancel-action').click();
      assert.equal(await p.locator('#day-0').inputValue(), '2');
      await action('save').click();
      await p.locator('#confirm-action').click();
      assert((await p.locator('[data-schedule=repair]').textContent()).includes('周二'));
      assert((await p.locator('[data-schedule=errands]').textContent()).includes('周二'));
      await nav('D');
      await p.locator('[data-remove-slot="0"]').click();
      assert(await focus('[data-action=add-slot]'));
      await p.locator('#back').click();
      await p.locator('#cancel-action').click();
      assert.equal(await p.locator('.schedule-row').count(), 0);
      await p.locator('#back').click();
      await p.locator('#confirm-action').click();
      assert((await p.locator('[data-schedule=repair]').textContent()).includes('周二'));
      assert(await p.evaluate(() => document.documentElement.scrollWidth <= innerWidth));
      await p.screenshot({ path: path.join(out, 'provider-' + width + '.png'), fullPage: true });
    }
    assert.deepEqual(errors, []);
    fs.writeFileSync(path.join(out, 'result.json'), JSON.stringify({ passed: true, widths: [320, 375, 414, 1280], checks: ['image and license focus', 'scroll and input retained', 'new and neighboring schedule focus', 'batch apply cancel and save'] }, null, 2));
    console.log('PASS provider field continuity');
  } finally { await browser.close(); }
}
main().catch(e => { console.error(e); process.exitCode = 1; });
